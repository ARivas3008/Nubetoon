  function translateStatic(){
    if(lang!=='en')return;
    const walker=document.createTreeWalker(document.body,NodeFilter.SHOW_TEXT);
    const nodes=[];
    while(walker.nextNode()){
      const n=walker.currentNode;
      if(n.parentElement?.closest('script,style,textarea,code'))continue;
      nodes.push(n);
    }
    for(const n of nodes){
      const raw=n.nodeValue,trimmed=raw.trim();
      if(Object.prototype.hasOwnProperty.call(english,trimmed)){
        n.nodeValue=raw.replace(trimmed,english[trimmed]);
      }
    }
    for(const element of document.querySelectorAll('[placeholder],[title],[aria-label],[alt]')){
      for(const name of ['placeholder','title','aria-label','alt']){
        const text=element.getAttribute(name);
        if(text&&Object.prototype.hasOwnProperty.call(english,text))element.setAttribute(name,english[text]);
      }
    }
    document.title=t(document.title);
  }
  function mountLanguageSelector(){
    const right=document.querySelector('.site-header .header-right');
    if(!right)return;
    const button=document.createElement('button');
    button.type='button';button.id='languageToggle';button.className='language-toggle';
    button.textContent=lang==='es'?'EN':'ES';
    button.title=lang==='es'?'Switch to English':'Cambiar a español';
    button.setAttribute('aria-label',button.title);
    button.setAttribute('lang',lang==='es'?'en':'es');
    button.addEventListener('click',()=>{
      const next=lang==='es'?'en':'es';
      try{localStorage.setItem(key,next);}catch{}
      location.reload();
    });
    right.prepend(button);
  }
